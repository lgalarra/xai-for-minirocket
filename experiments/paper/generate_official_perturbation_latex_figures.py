#!/usr/bin/env python3
"""Generate LaTeX figure* snippets for official perturbation charts."""

from __future__ import annotations

import argparse
import re
from dataclasses import dataclass
from pathlib import Path


SCRIPT_DIR = Path(__file__).resolve().parent
DEFAULT_SOURCE_DIR = SCRIPT_DIR / "official-perturbation-figures"
DEFAULT_OUTPUT = DEFAULT_SOURCE_DIR / "official_perturbation_figures.tex"
DEFAULT_LATEX_FIGURES_DIR = Path("figures")
DEFAULT_COLUMNS = 3
DEFAULT_ROWS_PER_FIGURE = 2
DEFAULT_CHARTS_PER_FIGURE = DEFAULT_COLUMNS * DEFAULT_ROWS_PER_FIGURE
DEFAULT_SOURCE_GROUPS = ("best_methods",)
EVOLUTION_FACTORS = ("percentile_cut", "interpolation", "sigma", "perturbation_policy")
METRIC_KINDS = ("probability-norm", "change-ratio", "probability")
EXPLAINER_LABELS = {
    "gradients": "Gradients",
    "shap": "SHAP",
    "stratoshap-k1": "ST-SHAP",
}
DATASET_LABELS = {
    "abnormal-heartbeat": "abnormal-heartbeat",
    "cognitive-circles": "cognitive-circles",
    "double-freq-test": "double-freq-test",
    "ford-a": "ford-a",
    "handoutlines": "handoutlines",
    "starlight": "starlight",
}
CLASSIFIER_LABELS = {
    "LogisticRegression": "LR",
    "MLPClassifier": "MLP",
    "RandomForestClassifier": "RF",
}
REFERENCE_POLICY_LABELS = {
    "counterfactual": "counterfactual",
    "global_centroid": "global centroid",
    "global_medoid": "global medoid",
    "opposite_class_centroid": "opposite centroid",
    "opposite_class_closest_instance": "opposite closest",
    "opposite_class_farthest_instance": "opposite farthest",
    "opposite_class_medoid": "opposite medoid",
}
FILENAME_RE = re.compile(
    rf"^(?P<dataset>.+?)_"
    rf"(?P<evolution_factor>{'|'.join(EVOLUTION_FACTORS)})_"
    rf"(?P<metric_kind>{'|'.join(METRIC_KINDS)})_"
    rf"(?P<perturbation_policy>.+?)_"
    rf"base-(?P<base_explainer>.+?)_"
    rf"reference-(?P<reference_policy>.+?)_"
    rf"model-(?P<model>.+?)"
    rf"(?:_best-random-(?P<best_random_regime>.+))?"
    rf"\.png$"
)


@dataclass(frozen=True)
class Chart:
    path: Path
    relative_path: Path
    dataset: str
    evolution_factor: str
    metric_kind: str
    perturbation_policy: str
    base_explainer: str
    reference_policy: str
    model: str
    best_random_regime: str | None
    group: str


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Write a LaTeX snippet with two figure* grids for PNGs generated by "
            "generate_all_official_perturbation_charts.py."
        )
    )
    parser.add_argument(
        "--source-dir",
        type=Path,
        default=DEFAULT_SOURCE_DIR,
        help=f"Directory containing generated PNGs. Default: {DEFAULT_SOURCE_DIR}",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
        help=f"Path where the LaTeX snippet is written. Default: {DEFAULT_OUTPUT}",
    )
    parser.add_argument(
        "--latex-figures-dir",
        type=Path,
        default=DEFAULT_LATEX_FIGURES_DIR,
        help=(
            "Directory prefix used in LaTeX \\includegraphics paths. "
            "Default: figures"
        ),
    )
    parser.add_argument(
        "--columns",
        type=int,
        default=DEFAULT_COLUMNS,
        help="Number of chart columns in each figure*. Default: 3.",
    )
    parser.add_argument(
        "--charts-per-figure",
        type=int,
        default=DEFAULT_CHARTS_PER_FIGURE,
        help=(
            "Maximum charts per figure* part. Default: 6, arranged as two "
            "rows of three charts."
        ),
    )
    parser.add_argument(
        "--source-group",
        action="append",
        dest="source_groups",
        default=None,
        help=(
            "Source subdirectory to include. May be repeated. "
            f"Default: {', '.join(DEFAULT_SOURCE_GROUPS)}."
        ),
    )
    parser.add_argument(
        "--flat-paths",
        action=argparse.BooleanOptionalAction,
        default=True,
        help=(
            "Use only PNG basenames in LaTeX paths instead of preserving paths "
            "relative to --source-dir. Default: true."
        ),
    )
    return parser.parse_args()


def latex_graphics_path(path: Path) -> str:
    return path.as_posix().replace("\\", "/")


def latex_escape(value: str) -> str:
    replacements = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    return "".join(replacements.get(char, char) for char in str(value))


def discover_charts(source_dir: Path, source_groups: tuple[str, ...]) -> list[Chart]:
    if not source_dir.exists():
        raise SystemExit(f"Source directory does not exist: {source_dir}")

    charts = []
    for path in sorted(source_dir.rglob("*.png")):
        relative_path = path.relative_to(source_dir)
        group = path.parent.name
        if source_groups and group not in source_groups:
            continue

        match = FILENAME_RE.match(path.name)
        if not match:
            print(f"Skipping PNG with unrecognized chart name: {path}")
            continue

        charts.append(
            Chart(
                path=path,
                relative_path=relative_path,
                group=group,
                **match.groupdict(),
            )
        )

    if not charts:
        raise SystemExit(
            "No official perturbation PNG charts found under "
            f"{source_dir} for source group(s): {', '.join(source_groups)}"
        )
    return charts


def chart_sort_key(chart: Chart) -> tuple[str, ...]:
    group_order = {"all_methods": "0", "best_methods": "1"}
    return (
        group_order.get(chart.group, chart.group),
        chart.dataset,
        chart.perturbation_policy,
        chart.base_explainer,
        chart.reference_policy,
        chart.model,
        chart.metric_kind,
        chart.path.name,
    )


def instance_to_reference_charts(charts: list[Chart]) -> list[Chart]:
    return sorted(
        (
            chart
            for chart in charts
            if chart.perturbation_policy == "instance_to_reference"
            and chart.base_explainer != "gradients"
        ),
        key=chart_sort_key,
    )


def reference_to_instance_charts(charts: list[Chart]) -> list[Chart]:
    return sorted(
        (
            chart
            for chart in charts
            if chart.perturbation_policy == "reference_to_instance"
        ),
        key=chart_sort_key,
    )


def gaussian_charts(charts: list[Chart]) -> list[Chart]:
    return sorted(
        (
            chart
            for chart in charts
            if "gaussian" in chart.perturbation_policy
            and (
                "random_no_positive" in chart.perturbation_policy
                or chart.best_random_regime == "random_no_positive"
            )
        ),
        key=chart_sort_key,
    )


def chunked(charts: list[Chart], chunk_size: int) -> list[list[Chart]]:
    if chunk_size < 1:
        raise SystemExit("--charts-per-figure must be at least 1")
    return [
        charts[index : index + chunk_size]
        for index in range(0, len(charts), chunk_size)
    ]


def chart_subcaption(chart: Chart) -> str:
    explainer = EXPLAINER_LABELS.get(chart.base_explainer, chart.base_explainer)
    dataset = DATASET_LABELS.get(chart.dataset, chart.dataset)
    qualifiers = []
    if chart.model != "all":
        qualifiers.append(CLASSIFIER_LABELS.get(chart.model, chart.model))
    if chart.reference_policy != "all":
        qualifiers.append(
            f"ref. {REFERENCE_POLICY_LABELS.get(chart.reference_policy, chart.reference_policy)}"
        )

    suffix = f" ({', '.join(qualifiers)})" if qualifiers else ""
    return latex_escape(f"{explainer} on {dataset}{suffix}")


def warn_about_flat_source_paths(charts: list[Chart], source_dir: Path) -> None:
    missing_flat_paths = [
        source_dir / chart.relative_path.name
        for chart in charts
        if not (source_dir / chart.relative_path.name).exists()
    ]
    if missing_flat_paths:
        groups = sorted({chart.group for chart in charts})
        group_text = ", ".join(f"{group}/" for group in groups)
        print(
            "Note: LaTeX paths are flat, but "
            f"{len(missing_flat_paths)} source PNG(s) are only present in "
            f"subdirectories: {group_text}."
        )
        print("      Copy or flatten those PNGs into your LaTeX figures/ directory.")


def write_figure(
    lines: list[str],
    charts: list[Chart],
    *,
    caption: str,
    label: str,
    columns: int,
    latex_figures_dir: Path,
    flat_paths: bool,
) -> None:
    if columns < 1:
        raise SystemExit("--columns must be at least 1")

    width = min(0.98 / columns, 0.98)
    lines.extend([r"\begin{figure*}[htbp]", r"\centering"])
    for index, chart in enumerate(charts, start=1):
        chart_path = chart.relative_path.name if flat_paths else chart.relative_path
        figure_path = latex_graphics_path(latex_figures_dir / chart_path)
        lines.extend(
            [
                rf"\begin{{subfigure}}[t]{{{width:.3f}\textwidth}}",
                r"\centering",
                rf"\includegraphics[width=\linewidth]{{{figure_path}}}",
                rf"\caption{{{chart_subcaption(chart)}}}",
                r"\end{subfigure}",
            ]
        )
        if index % columns == 0 and index != len(charts):
            lines.append(r"\par\medskip")
        elif index != len(charts):
            lines.append(r"\hfill")

    lines.extend(
        [
            rf"\caption{{{caption}}}",
            rf"\label{{{label}}}",
            r"\end{figure*}",
            "",
        ]
    )


def write_figure_parts(
    lines: list[str],
    charts: list[Chart],
    *,
    caption: str,
    label: str,
    columns: int,
    charts_per_figure: int,
    latex_figures_dir: Path,
    flat_paths: bool,
) -> None:
    parts = chunked(charts, charts_per_figure)
    for part_number, part_charts in enumerate(parts, start=1):
        part_caption = caption
        part_label = label
        if len(parts) > 1:
            part_caption = f"{caption} Part {part_number} of {len(parts)}."
            part_label = f"{label}-part-{part_number}"
        write_figure(
            lines,
            part_charts,
            caption=part_caption,
            label=part_label,
            columns=columns,
            latex_figures_dir=latex_figures_dir,
            flat_paths=flat_paths,
        )


def write_latex_figures(
    charts: list[Chart],
    source_dir: Path,
    output: Path,
    latex_figures_dir: Path,
    columns: int,
    charts_per_figure: int,
    flat_paths: bool,
) -> tuple[int, int, int]:
    instance_charts = instance_to_reference_charts(charts)
    reference_charts = reference_to_instance_charts(charts)
    gaussian_policy_charts = gaussian_charts(charts)
    if not instance_charts:
        raise SystemExit("No charts found for perturbation_policy=instance_to_reference")
    if not reference_charts:
        raise SystemExit("No charts found for perturbation_policy=reference_to_instance")
    if not gaussian_policy_charts:
        raise SystemExit(
            "No charts found with gaussian and random_no_positive in "
            "perturbation_policy"
        )
    if flat_paths:
        warn_about_flat_source_paths(
            instance_charts + reference_charts + gaussian_policy_charts,
            source_dir,
        )

    lines = [
        "% Generated by generate_official_perturbation_latex_figures.py.",
        "% Assumes these PNG files are available under the LaTeX figures/ directory.",
        "% Requires \\usepackage{graphicx}.",
        "% Requires \\usepackage{subcaption}.",
        "",
    ]
    write_figure_parts(
        lines,
        instance_charts,
        caption=(
            "Official perturbation charts for the occlusion perturbation regime."
        ),
        label="fig:official-perturbation-instance-to-reference",
        columns=columns,
        charts_per_figure=charts_per_figure,
        latex_figures_dir=latex_figures_dir,
        flat_paths=flat_paths,
    )
    write_figure_parts(
        lines,
        reference_charts,
        caption=(
            "Official perturbation charts for the reference-to-instance policy."
        ),
        label="fig:official-perturbation-reference-to-instance",
        columns=columns,
        charts_per_figure=charts_per_figure,
        latex_figures_dir=latex_figures_dir,
        flat_paths=flat_paths,
    )
    write_figure_parts(
        lines,
        gaussian_policy_charts,
        caption=(
            "Official perturbation charts for the noise addition perturbation regime."
        ),
        label="fig:official-perturbation-gaussian",
        columns=columns,
        charts_per_figure=charts_per_figure,
        latex_figures_dir=latex_figures_dir,
        flat_paths=flat_paths,
    )

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines), encoding="utf-8")
    return len(instance_charts), len(reference_charts), len(gaussian_policy_charts)


def main() -> None:
    args = parse_args()
    source_groups = tuple(args.source_groups or DEFAULT_SOURCE_GROUPS)
    charts = discover_charts(args.source_dir, source_groups)
    instance_count, reference_count, gaussian_count = write_latex_figures(
        charts,
        args.source_dir,
        args.output,
        args.latex_figures_dir,
        args.columns,
        args.charts_per_figure,
        args.flat_paths,
    )
    print(f"Wrote LaTeX figure snippet: {args.output}")
    print(f"Instance-to-reference charts: {instance_count}")
    print(f"Reference-to-instance charts: {reference_count}")
    print(f"Gaussian charts: {gaussian_count}")


if __name__ == "__main__":
    main()
